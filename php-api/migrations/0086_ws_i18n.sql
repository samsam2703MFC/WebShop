-- 0086 — Table de traduction du webshop (source unique, éditable).
--
-- Demandé : « rien en dur, tout lié à la table de traduction ». Les libellés
-- d'interface ne vivent plus dans le JS : ils sont ici, servis par GET /i18n
-- et chargés au boot. Ce n'est PAS un seed de démo (règle « aucune donnée
-- inventée ») — c'est le VRAI texte de l'app, relogé pour devenir éditable.
--
-- scope='ui'  : chrome de l'interface (boutons, titres, messages).
-- Le CONTENU (noms produits/catégories) reste servi par l'API catalogue
-- (marque) — il n'a pas sa place ici.
--
-- IDEMPOTENTE : CREATE ... IF NOT EXISTS ; INSERT IGNORE => une ré-exécution
-- n'écrase JAMAIS une valeur éditée après coup (seules les clés manquantes
-- sont réinsérées).

CREATE TABLE IF NOT EXISTS ws_i18n (
  scope      VARCHAR(24)  NOT NULL DEFAULT 'ui',
  k          VARCHAR(80)  NOT NULL,
  lang       VARCHAR(5)   NOT NULL,
  value      TEXT         NOT NULL,
  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (scope, k, lang)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

